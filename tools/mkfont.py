#!/usr/bin/env python3
"""Renders printable ASCII from a monospace TTF into a 1-bit C table."""
import sys
from PIL import Image, ImageDraw, ImageFont

ttf, size, out = sys.argv[1], int(sys.argv[2]), sys.argv[3]
font = ImageFont.truetype(ttf, size)
ascent, descent = font.getmetrics()
cell_w = int(round(font.getlength("M")))
cell_h = ascent + descent
assert cell_w <= 16

rows = []
for code in range(32, 127):
    img = Image.new("1", (cell_w, cell_h), 0)
    draw = ImageDraw.Draw(img)
    draw.fontmode = "1"                      # no anti-aliasing
    draw.text((0, 0), chr(code), font=font, fill=1)
    glyph = []
    for y in range(cell_h):
        bits = 0
        for x in range(cell_w):
            if img.getpixel((x, y)):
                bits |= 0x8000 >> x
        glyph.append(bits)
    rows.append(glyph)

with open(out, "w") as f:
    f.write("/* Generated by tools/mkfont.py - do not edit. */\n")
    f.write(f"#define FONT_W {cell_w}\n#define FONT_H {cell_h}\n")
    f.write("static const unsigned short font_rows[95][FONT_H] = {\n")
    for code, glyph in zip(range(32, 127), rows):
        f.write("    {" + ",".join(f"0x{b:04X}" for b in glyph) + "},\n")
    f.write("};\n")
print(f"cell {cell_w}x{cell_h}")
